import { spawn } from 'node:child_process';
import { existsSync, readFileSync, rmSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve, join } from 'node:path';
const profile = resolve('tmp/profile'); rmSync(profile, { recursive: true, force: true });
const chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', ['--headless=new', '--remote-debugging-port=0', `--user-data-dir=${profile}`, '--no-first-run', 'about:blank'], { stdio: 'ignore' });
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
for (let i = 0; i < 200 && !existsSync(join(profile, 'DevToolsActivePort')); i++) await sleep(50);
await sleep(100);
const [port, p] = readFileSync(join(profile, 'DevToolsActivePort'), 'utf8').trim().split('\n');
const ws = new WebSocket(`ws://127.0.0.1:${port}${p}`); await new Promise(r => ws.onopen = r);
let id = 0; const pend = new Map(); const ev = [];
ws.onmessage = m => { const x = JSON.parse(m.data); if (x.id && pend.has(x.id)) { pend.get(x.id)(x); pend.delete(x.id); } else ev.push(x); };
const send = (method, params = {}, sessionId) => new Promise(r => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params, sessionId })); });
const t = (await send('Target.createTarget', { url: 'about:blank' })).result.targetId;
const s = (await send('Target.attachToTarget', { targetId: t, flatten: true })).result.sessionId;
const S = (m, q) => send(m, q, s);
await S('Runtime.enable'); await S('Page.enable');
await S('Emulation.setDeviceMetricsOverride', { width: 1400, height: 900, deviceScaleFactor: 1, mobile: false });
await S('Page.navigate', { url: pathToFileURL(resolve('dev/preview.html')).href });
await sleep(1500);
const js = async (e) => (await S('Runtime.evaluate', { expression: e, returnByValue: true })).result;
console.log(JSON.stringify(await js(`(() => { document.querySelector('#atlas-r-beta-hub th .atlas-link').click(); const p = document.querySelector('.atlas-pane');
 return { hash: location.hash, html: p.innerHTML.slice(0, 600), hidden: p.hidden }; })()`)).slice(0, 1500));
for (const e of ev) if (e.method === 'Runtime.exceptionThrown') console.log('EXC', JSON.stringify(e.params.exceptionDetails).slice(0, 800));
await send('Browser.close'); chrome.kill(); rmSync(profile, { recursive: true, force: true });
